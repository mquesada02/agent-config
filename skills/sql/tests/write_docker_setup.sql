CREATE FUNCTION pgw.noop() RETURNS trigger LANGUAGE plpgsql AS $f$
BEGIN
  IF TG_LEVEL = 'STATEMENT' THEN RETURN NULL; END IF;
  RETURN COALESCE(NEW, OLD);
END $f$;
